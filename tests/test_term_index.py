def test_the_source_validator_is_the_only_source_check(tmp_path: Path) -> None:
    proj = _project(tmp_path, _reg(_term("a", "alpha", source=["k1", "k2"]), _term("b", "beta", source=None)),
                    {"a.md": "alpha beta"})
