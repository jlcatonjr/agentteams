FIXTURE = Path(__file__).parent / "fixtures" / "term_index_rt_compat"
RT_REFS = re.compile(r"^#{1,6}[ \t]+([Rr]eferences|[Bb]ibliography|[Ww]orks [Cc]ited|[Ss]ources)([ \t].*)?$")
RT_CONFIG = ti.TermIndexConfig(
    generator="researchteam-term-index/1", skip_heading=RT_REFS,
    do_not_edit=("GENERATED by scripts/build_term_index.py from terminology/terms.json. Do not edit. "
                 "Rebuild: bash scripts/claude_researchteam_bridge.sh term-build <project>"),
    glossary_hint="Where each term occurs: `bash scripts/claude_researchteam_bridge.sh term-query`.")


def _reg(*terms: dict, **top) -> dict:
    return {"schema": ti.NEUTRAL_SCHEMA, "terms": list(terms), **top}


def _term(tid: str, label: str, **kw) -> dict:
    return {"id": tid, "label": label, "definition": f"the {label}", "source": "project definition", **kw}


def _project(tmp_path: Path, reg: dict, docs: dict[str, str]) -> Path:
    (tmp_path / "terminology").mkdir(parents=True, exist_ok=True)
    (tmp_path / "terminology" / "terms.json").write_text(json.dumps(reg), encoding="utf-8")
    for rel, text in docs.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(text, encoding="utf-8")
    return tmp_path


def _build(proj: Path, config: ti.TermIndexConfig = ti.TermIndexConfig()) -> None:
    for rel, data in ti.assess(proj, config).files.items():
        (proj / config.dir_name / rel).parent.mkdir(parents=True, exist_ok=True)
        (proj / config.dir_name / rel).write_bytes(data)


def _occ(reg: dict, text: str) -> list[tuple[str, str, bool]]:
    return [(o["term"], o["form"], o["quoted"]) for o in Matcher(reg).occurrences(text)]


