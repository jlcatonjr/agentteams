# 16: upsert -------------------------------------------------------------------------------------

def test_upsert_changes_only_the_fence() -> None:
    block = grok_runtime_block()
    original = "# Mine\n\nKeep this *exactly*.\n"
    once = own.upsert_fenced_block(original, own.GROK_FENCE_ID, block)
    assert once.startswith(original.rstrip("\n")) and once.endswith(block + "\n")
    assert own.upsert_fenced_block(once, own.GROK_FENCE_ID, block) == once
    refreshed = once.replace("Grok Build Notes", "Old Notes")
    assert own.upsert_fenced_block(refreshed, own.GROK_FENCE_ID, block) == once
    with pytest.raises(ValueError):
        own.upsert_fenced_block(once + "\n" + block, own.GROK_FENCE_ID, block)
    with pytest.raises(ValueError):
        own.upsert_fenced_block(original, own.GROK_FENCE_ID, "not a fence")


# Grok guard -------------------------------------------------------------------------------------

def test_guard_absent_and_grok_owned_keep_full_render(tmp_path: Path) -> None:
    root, agents = _project(tmp_path)
    kept, _ = GrokAdapter().guard_rendered_files([("../../AGENTS.md", "full")], agents)
    assert kept == [("../../AGENTS.md", "full")]
    (root / "AGENTS.md").write_text(GROK_AGENTS_MD_NOTICE + "\n", encoding="utf-8")
    kept, _ = GrokAdapter().guard_rendered_files([("../../AGENTS.md", "full")], agents)
    assert kept == [("../../AGENTS.md", "full")]


@pytest.mark.parametrize("existing", [_CODEX_FILE, _AGENTS_MD_NOTICE + "\n\n# Team\n", _FENCED_GOOSE])
def test_guard_upserts_into_agentteams_owned(tmp_path: Path, existing: str) -> None:
    root, agents = _project(tmp_path)
    (root / "AGENTS.md").write_text(existing, encoding="utf-8")
    kept, notices = GrokAdapter().guard_rendered_files([("../../AGENTS.md", "full")], agents)
