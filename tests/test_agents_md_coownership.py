# 17–18: through emit_all -------------------------------------------------------------------------

def _emit(agents: Path, files: list[tuple[str, str]], **kw) -> None:
    kept, _ = GrokAdapter().guard_rendered_files(files, agents)
    emit_all(kept, output_dir=agents, yes=True, **kw)


@pytest.mark.parametrize("mode", [{}, {"overwrite": True}, {"merge": True}])
def test_hand_written_is_byte_identical_in_every_mode(tmp_path: Path, mode: dict) -> None:
    root, agents = _project(tmp_path)
    original = "# Mine\n\nDo not touch.\n"
    (root / "AGENTS.md").write_text(original, encoding="utf-8")
    _emit(agents, [("../../AGENTS.md", GrokAdapter().render_instructions_file("# T\n", {}))], **mode)
    assert (root / "AGENTS.md").read_text(encoding="utf-8") == original
    assert (root / ".grok" / "examples" / "AGENTS.grok-block.md").is_file()


@pytest.mark.parametrize("existing", [_CODEX_FILE, _FENCED_GOOSE])
def test_merge_keeps_every_byte_outside_the_fence(tmp_path: Path, existing: str) -> None:
    root, agents = _project(tmp_path)
    (root / "AGENTS.md").write_text(existing, encoding="utf-8")
    _emit(agents, [("../../AGENTS.md", GrokAdapter().render_instructions_file("# T\n", {}))], merge=True)
    after = (root / "AGENTS.md").read_text(encoding="utf-8")
    assert after.count(f"AGENTTEAMS:BEGIN {own.GROK_FENCE_ID}") == 1
    start = after.index(f"<!-- AGENTTEAMS:BEGIN {own.GROK_FENCE_ID}")
    assert after[:start].rstrip("\n") == existing.rstrip("\n")


def test_unfenced_agentteams_file_is_left_alone_on_merge(tmp_path: Path) -> None:
    """A generated but unfenced AGENTS.md (pre-fence render) is not rewritten by merge: safe, not clobbered."""
    root, agents = _project(tmp_path)
    (root / "AGENTS.md").write_text(_UNFENCED_CODEX, encoding="utf-8")
    _emit(agents, [("../../AGENTS.md", GrokAdapter().render_instructions_file("# T\n", {}))], merge=True)
    assert (root / "AGENTS.md").read_text(encoding="utf-8") == _UNFENCED_CODEX


def test_grok_owned_file_keeps_user_text_outside_fences_on_merge(tmp_path: Path) -> None:
    root, agents = _project(tmp_path)
    first = GrokAdapter().render_instructions_file("<!-- AGENTTEAMS:BEGIN team v=1 -->\n# T\n"
                                                  "<!-- AGENTTEAMS:END team -->\n", {})
    (root / "AGENTS.md").write_text(first + "\nMy own note.\n", encoding="utf-8")
    _emit(agents, [("../../AGENTS.md", first)], merge=True)
    assert "My own note." in (root / "AGENTS.md").read_text(encoding="utf-8")


