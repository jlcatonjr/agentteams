"""Shared repo-root AGENTS.md co-ownership (``frameworks/_agents_md_ownership.py``; Grok decision D2).

Covers the Component Brief's checklist (tmp/by-week/2026-W42/grok-adapter.brief.md §8, items 14–21):

* the classification truth table (absent, symlinks, unreadable, every generated owner, fenced, foreign,
  malformed; a marker quoted later in the file never confers ownership);
* Codex's ownership answer is unchanged, and it never touches a Grok-owned file;
* ``upsert_fenced_block`` changes nothing outside its fence and refuses duplicates;
* the Grok guard: full write when absent or Grok-owned, ``grok_runtime`` upsert into agentteams-owned files, a
  paste-in example (never a write) for hand-written files, nothing for unsafe ones, symlinked parents refused;
* through ``emit_all``: outside-fence bytes survive, and a hand-written AGENTS.md is byte-identical in every mode.
"""

from __future__ import annotations

import os
from pathlib import Path

import pytest

from agentteams.emit import emit_all
from agentteams.frameworks import _agents_md_ownership as own
from agentteams.frameworks.agents_md import _AGENTS_MD_NOTICE
from agentteams.frameworks.codex import CodexAdapter, agents_md_is_codex_owned
from agentteams.frameworks.grok import GROK_AGENTS_MD_NOTICE, GrokAdapter, grok_runtime_block

_FENCED_GOOSE = "<!-- AGENTTEAMS:BEGIN team_overview v=1 -->\n# Team\n<!-- AGENTTEAMS:END team_overview -->\n"
_CODEX_FILE = ("<!-- AGENTS.md — generated by agentteams for OpenAI Codex. x -->\n\n"
               "<!-- AGENTTEAMS:BEGIN team_overview v=1 -->\n# Team\n<!-- AGENTTEAMS:END team_overview -->\n")
_UNFENCED_CODEX = "<!-- AGENTS.md — generated by agentteams for OpenAI Codex. x -->\n\n# Team\n"


def _project(tmp_path: Path) -> tuple[Path, Path]:
    root = tmp_path / "proj"
    agents = root / ".grok" / "agents"
    agents.mkdir(parents=True)
    return root, agents


# 14: classification -----------------------------------------------------------------------------

@pytest.mark.parametrize("text, expected", [
    (GROK_AGENTS_MD_NOTICE + "\n\n# Team\n", own.GROK),
    (_CODEX_FILE, own.CODEX),
    (_AGENTS_MD_NOTICE + "\n\n# Team\n", own.AGENTS_MD),
    (_FENCED_GOOSE, own.FENCED),
    ("# My hand-written instructions\n", own.FOREIGN),
    ("# Mine\n\n" + GROK_AGENTS_MD_NOTICE + "\n", own.FOREIGN),  # quoted marker: not ownership
    ("<!-- AGENTTEAMS:BEGIN a v=1 -->\nunclosed\n", own.UNSAFE),
])
def test_classify(tmp_path: Path, text: str, expected: str) -> None:
    p = tmp_path / "AGENTS.md"
    p.write_text(text, encoding="utf-8")
    assert own.classify_agents_md(p) == expected


def test_classify_absent_symlink_and_binary(tmp_path: Path) -> None:
    p = tmp_path / "AGENTS.md"
    assert own.classify_agents_md(p) == own.ABSENT
    (tmp_path / "real.md").write_text("x")
    p.symlink_to(tmp_path / "real.md")
    assert own.classify_agents_md(p) == own.UNSAFE
    p.unlink()
    p.symlink_to(tmp_path / "missing.md")  # dangling
    assert own.classify_agents_md(p) == own.UNSAFE
    p.unlink()
    p.write_bytes(b"\xff\xfe\x00bad")
    assert own.classify_agents_md(p) == own.UNSAFE


def test_classify_refuses_symlinked_parent_and_escape(tmp_path: Path) -> None:
    root = tmp_path / "proj"
    root.mkdir()
    outside = tmp_path / "outside"
    outside.mkdir()
    (root / "link").symlink_to(outside, target_is_directory=True)
    assert own.classify_agents_md(root / "link" / "AGENTS.md", repo_root=root) == own.UNSAFE
    assert own.classify_agents_md(root / "AGENTS.md", repo_root=root) == own.ABSENT


def test_agents_md_notice_starts_with_the_shared_neutral_marker() -> None:
    assert _AGENTS_MD_NOTICE.startswith(own.NEUTRAL_AGENTS_MD_MARKER)


