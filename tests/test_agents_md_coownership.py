def test_grok_then_codex_codex_skips(tmp_path: Path) -> None:
    root, agents = _project(tmp_path)
    _emit(agents, [("../../AGENTS.md", GrokAdapter().render_instructions_file("# T\n", {}))])
    before = (root / "AGENTS.md").read_text(encoding="utf-8")
    out = root / ".codex" / "agents"
    out.mkdir(parents=True)
    kept, _ = CodexAdapter().guard_rendered_files([("../../AGENTS.md", "codex")], out)
    assert kept == [] and (root / "AGENTS.md").read_text(encoding="utf-8") == before


def test_codex_then_grok_then_codex_keeps_codex_owner(tmp_path: Path) -> None:
    root, agents = _project(tmp_path)
    (root / "AGENTS.md").write_text(_CODEX_FILE, encoding="utf-8")
    _emit(agents, [("../../AGENTS.md", GrokAdapter().render_instructions_file("# T\n", {}))], merge=True)
    text = (root / "AGENTS.md").read_text(encoding="utf-8")
    assert text.startswith(own.CODEX_AGENTS_MD_MARKER) and grok_runtime_block() in text
    assert agents_md_is_codex_owned(root / "AGENTS.md")
    assert os.path.exists(root / "AGENTS.md")
