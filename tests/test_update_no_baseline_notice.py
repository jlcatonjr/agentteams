"""One up-front notice when an ``--update`` merges a team with no generation baseline (issue #392 item 15).

A team whose ``build-log.json`` records no fence digests (every team generated by 1.1.x or earlier) cannot have
an older template's text told apart from an edit, so each changed fence is preserved with its own shrink notice.
The run now says so once, before any file is written, and names the path that works: preview
``--update --overwrite --dry-run --json``, then run it. ``--capture-baseline`` is not that path.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

import build_team
from agentteams import fence_baseline
from agentteams.cli.update_notices import NO_BASELINE, no_baseline_notice
from tests.test_update_dry_run import _seed_gates, _seed_pass

REPO = Path(__file__).resolve().parents[1]
EXAMPLE = REPO / "examples" / "data-pipeline" / "brief.json"
FIRST_LINE = NO_BASELINE.splitlines()[0].strip()


@pytest.fixture
def team(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> tuple[Path, Path]:
    brief = json.loads(EXAMPLE.read_text(encoding="utf-8"))
    brief["enforce_decision_signing"] = False
    brief_path = tmp_path / "brief.json"
    brief_path.write_text(json.dumps(brief), encoding="utf-8")
    out = tmp_path / ".github" / "agents"
    _seed_gates(out, monkeypatch)
    assert build_team.main(["--description", str(brief_path), "--output", str(out),
                            "--yes", "--no-scan", "--security-offline"]) == 0
    _seed_pass(out)
    return brief_path, out


def _drop_baseline(out: Path) -> None:
    log_path = out / "references" / "build-log.json"
    log = json.loads(log_path.read_text(encoding="utf-8"))
    assert log.pop(fence_baseline.BUILD_LOG_KEY, None), "precondition: a fresh team records a baseline"
    log_path.write_text(json.dumps(log, indent=2), encoding="utf-8")


def _update(team: tuple[Path, Path], *extra: str) -> int:
    brief, out = team
    return build_team.main(["--description", str(brief), "--output", str(out), "--update", *extra,
                            "--yes", "--no-scan", "--security-offline"])


def test_a_team_without_a_baseline_gets_one_notice_up_front(team: tuple[Path, Path], capsys) -> None:
    _drop_baseline(team[1])
    capsys.readouterr()
    assert _update(team, "--dry-run", "--json") == 0
    err = capsys.readouterr().err
    assert err.count(FIRST_LINE) == 1
    assert "--update --overwrite --dry-run --json" in err
    assert "--capture-baseline does not" in err


def test_a_team_with_a_baseline_gets_no_notice(team: tuple[Path, Path], capsys) -> None:
    capsys.readouterr()
    assert _update(team, "--dry-run", "--json") == 0
    assert FIRST_LINE not in capsys.readouterr().err


def test_a_real_merge_records_the_baseline_so_the_notice_does_not_repeat(team: tuple[Path, Path], capsys) -> None:
    _drop_baseline(team[1])
    assert _update(team) == 0
    assert fence_baseline.load_for(team[1]), "the merge should record fences it wrote as rendered"
    capsys.readouterr()
    assert _update(team, "--dry-run", "--json") == 0
    assert FIRST_LINE not in capsys.readouterr().err


class _Args:
    def __init__(self, overwrite: bool) -> None:
        self.overwrite = overwrite


def test_overwrite_prints_nothing_and_a_missing_log_counts_as_no_baseline(tmp_path: Path, capsys) -> None:
    assert no_baseline_notice(tmp_path, _Args(overwrite=True)) is False
    assert no_baseline_notice(tmp_path, _Args(overwrite=False)) is True
    assert capsys.readouterr().err.count(FIRST_LINE) == 1
