CRATES_GIT = "registry+https://github.com/rust-lang/crates.io-index"
CRATES_SPARSE = "sparse+https://index.crates.io/"

LOCK_V3 = f'''# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "demo"
version = "0.1.0"
dependencies = ["smallvec", "time"]

[[package]]
name = "smallvec"
version = "1.6.0"
source = "{CRATES_GIT}"
checksum = "fe0f37c9e8f3c5a4a66ad655a93c74daac4ad00c441533bf5c6e7990bb42604e"

[[package]]
name = "time"
version = "0.3.0"
source = "{CRATES_GIT}"

[[package]]
name = "forked"
version = "0.2.0"
source = "git+https://github.com/example/forked?rev=abc#abc"

[[package]]
name = "inhouse"
version = "1.0.0"
source = "registry+https://crates.example.org/index"
'''

# v4 (Cargo 1.78+): the sparse index; v1 had no top-level version and checksums under [metadata]
LOCK_V4 = f'''version = 4

[[package]]
name = "ws-member"
version = "0.1.0"

[[package]]
name = "openssl"
version = "0.10.40"
source = "{CRATES_SPARSE}"
checksum = "00"
'''

LOCK_V1 = f'''[[package]]
name = "demo"
version = "0.1.0"
dependencies = ["libc 0.2.80 ({CRATES_GIT})"]

[[package]]
name = "libc"
version = "0.2.80"
source = "{CRATES_GIT}"

[metadata]
"checksum libc 0.2.80 ({CRATES_GIT})" = "00"
'''


def _write(path: Path, text: str) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return path


def _pairs(m: manifests.Manifest) -> list[tuple[str, str, str, str]]:
    return [(d.ecosystem, d.name, d.version, d.scope) for d in m.deps]


# ---------------------------------------------------------------- parsing


def test_v3_lock_reads_crates_io_packages_and_skips_path_git_and_other_registries(tmp_path: Path) -> None:
    m = manifests.parse(_write(tmp_path / "Cargo.lock", LOCK_V3))
    assert m.unscannable == ""
    assert _pairs(m) == [("crates.io", "smallvec", "1.6.0", "runtime"), ("crates.io", "time", "0.3.0", "runtime")]
    assert {d.source for d in m.deps} == {str(tmp_path / "Cargo.lock")}


def test_v4_sparse_and_v1_lock_formats(tmp_path: Path) -> None:
    v4 = manifests.parse(_write(tmp_path / "v4" / "Cargo.lock", LOCK_V4))
    assert _pairs(v4) == [("crates.io", "openssl", "0.10.40", "runtime")]
    v1 = manifests.parse(_write(tmp_path / "v1" / "Cargo.lock", LOCK_V1))
    assert _pairs(v1) == [("crates.io", "libc", "0.2.80", "runtime")]


@pytest.mark.parametrize("text", [
    "version = 3\n",
    'version = 3\n[[package]]\nname = "only-local"\nversion = "0.1.0"\n',
    'version = 3\n[[package]]\nname = "g"\nversion = "1.0.0"\nsource = "git+https://example.org/g#00"\n'])
def test_lock_without_crates_io_packages_is_unscannable(tmp_path: Path, text: str) -> None:
    m = manifests.parse(_write(tmp_path / "Cargo.lock", text))
    assert not m.deps and m.unscannable == "no crates.io packages"


@pytest.mark.parametrize("text", [
    "version = 3\n[[package]\n",                                        # not TOML
    'package = ["x"]\n',                                                # package entries are not tables
    b"\xff\xfe".decode("latin-1")])                                     # not UTF-8 once written as latin-1
def test_malformed_lock_is_unscannable_and_never_raises(tmp_path: Path, text: str) -> None:
    path = tmp_path / "Cargo.lock"
    path.write_bytes(text.encode("latin-1"))
    m = manifests.parse(path)
    assert not m.deps and m.unscannable.startswith("could not parse")


def test_a_crates_io_entry_without_a_name_is_unscannable(tmp_path: Path) -> None:
    path = tmp_path / "Cargo.lock"
    path.write_text(f'[[package]]\nversion = "1.0.0"\nsource = "{CRATES_GIT}"\n', encoding="utf-8")
    m = manifests.parse(path)
    assert not m.deps and m.unscannable == "a crates.io entry with an unusual name or version: not read"


def test_cargo_lock_is_no_longer_an_unsupported_ecosystem() -> None:
    assert manifests.unsupported_ecosystem("Cargo.lock") == ""
    assert "Cargo.lock" not in manifests.LOCKFILES   # it must not hide a sibling package.json/pyproject.toml


# ---------------------------------------------------------------- discovery


def test_mixed_directory_keeps_reporting_a_package_json_without_lockfile(tmp_path: Path) -> None:
    _write(tmp_path / "Cargo.lock", LOCK_V3)
    _write(tmp_path / "package.json", '{"name": "wasm-demo"}')
    _write(tmp_path / "pyproject.toml", '[project]\nname = "maturin-demo"\n')
    found = {p.name for p in manifests.discover(tmp_path)}
    assert found == {"Cargo.lock", "package.json", "pyproject.toml"}
    assert "without a lockfile" in manifests.parse(tmp_path / "package.json").unscannable


def test_discovery_skips_leans_lake_package_cache(tmp_path: Path) -> None:
    _write(tmp_path / "lake-manifest.json", "{}")
    _write(tmp_path / ".lake" / "packages" / "mathlib" / "lake-manifest.json", "{}")
    _write(tmp_path / ".lake" / "packages" / "tool" / "Cargo.lock", LOCK_V3)
    _write(tmp_path / ".lake" / "packages" / "tool" / "requirements.txt", "lib-a==1.0\n")
    assert [p.relative_to(tmp_path).as_posix() for p in manifests.discover(tmp_path)] == ["lake-manifest.json"]


# ---------------------------------------------------------------- engine end to end


def test_scan_finds_a_vulnerable_crate_and_withholds_private_ones(tmp_path: Path, feed: Feed) -> None:  # noqa: F811
    repo = tmp_path / "app"
    (repo / ".git").mkdir(parents=True)
    _write(repo / "Cargo.lock", LOCK_V3 + f'\n[[package]]\nname = "acme_core"\nversion = "2.0.0"\n'
                                         f'source = "{CRATES_GIT}"\n')
    _write(repo / ".agentteams" / "brief.json", json.dumps({
        "project_goal": "a goal for tests", pp.POLICY_KEY: {"level": "scan", "private_packages": ["acme-*"]}}))
    feed.vulns[("crates.io", "smallvec", "1.6.0")] = ["RUSTSEC-2021-0003"]
    feed.records["RUSTSEC-2021-0003"] = _adv("RUSTSEC-2021-0003", "crates.io", "smallvec", "1.0.0", "1.6.1")
    rep = engine.scan_path(tmp_path)
    assert rep.feed_errors == [] and rep.unscannable == []
    assert rep.withheld == ["app: acme_core (crates.io)"]   # Cargo treats - and _ alike
    [f] = rep.findings
    assert (f.ecosystem, f.name, f.version, f.fix, f.scope) == ("crates.io", "smallvec", "1.6.0", "1.6.1", "runtime")
    assert f.locations == ["app/Cargo.lock"]


def test_is_private_treats_dash_and_underscore_alike_only_for_crates() -> None:
    assert pp.is_private("Acme_Core", ["acme-*"], "crates.io")
    assert pp.is_private("acme-core", ["ACME_CORE"], "crates.io")
    assert not pp.is_private("acme_core", ["acme-*"], "npm")


# ---------------------------------------------------------------- fix plan (plan only)


def test_fix_plan_is_plan_only_and_never_edits_the_lock(tmp_path: Path, feed: Feed) -> None:  # noqa: F811
    lock = _write(tmp_path / "Cargo.lock", LOCK_V3)
    feed.vulns[("crates.io", "smallvec", "1.6.0")] = ["RUSTSEC-2021-0003"]
    feed.records["RUSTSEC-2021-0003"] = _adv("RUSTSEC-2021-0003", "crates.io", "smallvec", "1.0.0", "1.6.1")
    feed.vulns[("crates.io", "time", "0.3.0")] = ["RUSTSEC-2020-0071"]
    feed.records["RUSTSEC-2020-0071"] = _adv("RUSTSEC-2020-0071", "crates.io", "time", "0.0.0", None)
    before = lock.read_bytes()
    for apply in (False, True):
        res = fix.fix_path(tmp_path, apply=apply, npm=False, allow_dirty=True)
        assert lock.read_bytes() == before and res.changes == [] and res.feed_errors == []
        assert [(c.name, c.old, c.new, c.action) for c in res.cargo_plan] == [
            ("smallvec", "1.6.0", "1.6.1", "plan-only"), ("time", "0.3.0", "", "no-clean-release")]
        assert res.exit_code() == 1   # something is left for a person
    md = res.markdown()
    assert "## crates.io: `Cargo.lock` — plan-only (no staged edit)" in md
    assert "do not request `stage-fix`" in md
    assert "`cargo update -p smallvec@1.6.0 --precise 1.6.1`" in md


def test_fix_plan_withholds_private_crates_and_flags_malicious(tmp_path: Path, feed: Feed,  # noqa: F811
                                                               monkeypatch: pytest.MonkeyPatch) -> None:
    _write(tmp_path / "Cargo.lock", LOCK_V3)
    feed.vulns[("crates.io", "time", "0.3.0")] = ["MAL-2026-1"]
    sent: list[str] = []

    def recording(url: str, payload: dict | None = None, **kw: object) -> object:
        sent.extend(q["package"]["name"] for q in (payload or {}).get("queries", []))
        return feed(url, payload, **kw)

    monkeypatch.setattr(_http, "fetch_json", recording)
    rows = fix.plan_cargo_lock(tmp_path / "Cargo.lock", label="Cargo.lock", private=("SMALLVEC*",))
    assert [(c.name, c.action, c.new) for c in rows] == [("time", "malicious", "")]
    assert sent == ["time"]   # a private crate never leaves the machine


