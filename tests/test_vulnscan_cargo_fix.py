def test_stage_cargo_is_its_own_grantable_op() -> None:
    assert "stage-cargo" in grant.OPS_V1 and "stage-cargo" in ops.STAGE_OPS and "stage-cargo" in ops.REPO_OPS
    g = {"ops": ["stage-fix", "stage-major"], "repo_roots": ["/r"], "hosts": []}
    assert not grant.covers(g, "stage-cargo", "/r/x")   # a grant listing stage-fix never implies it


def test_validate_diff_accepts_only_cargo_lock_under_stage_cargo(env: dict) -> None:
    from agentteams.vulnscan import executor
    from tests.test_vulnscan_executor import GIT, _git_repo
    if not GIT:
        pytest.skip("git not available")
    repo = _git_repo(env["tmp"] / "r")
    (repo / "Cargo.toml").write_text(TOML)
    (repo / "Cargo.lock").write_text(_lock())
    for args in (["add", "-A"], ["-c", "user.email=t@t", "-c", "user.name=t", "commit", "-qm", "base"]):
        subprocess.run(["git", "-C", str(repo), *args], check=True, capture_output=True)
    base = subprocess.run(["git", "-C", str(repo), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    (repo / "Cargo.lock").write_text(_lock("0.13.4", "7.4.0"))
    assert executor.validate_diff(repo, base, mode="cargo").changed == ["Cargo.lock"]
    with pytest.raises(ExecError, match="outside dependency pins"):
        executor.validate_diff(repo, base, mode="fix")   # stage-fix still never edits a Cargo.lock
    (repo / "Cargo.toml").write_text(TOML.replace('"0.13"', '"0.14"'))
    with pytest.raises(ExecError, match="outside Cargo.lock"):
        executor.validate_diff(repo, base, mode="cargo")
