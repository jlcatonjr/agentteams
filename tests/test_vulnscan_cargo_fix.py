"""vfr-d.D3: ``stage-cargo``, in-major ``cargo update --precise`` fixes on a ``Cargo.lock`` (operator decision OD9).

Fixture: baseAgent's ``serve/deploy/component-host`` shape (zstd 0.13.3 -> zstd-safe 7.2.4 -> zstd-sys 2.1.2). The
advisory data is a fixture, not the real OSV record (that could not be fetched here; see the PR's Rule 14 note).
``@security`` conditions: Rule 14 check (here: the S-10 search on the target decides), crates.io only, Cargo.toml
unchanged, no new [[package]], S-10 search. Network-free: OSV and cargo are fakes.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

import pytest

from agentteams.vulnscan import cargo_fix, fix, grant, ops, osv, retry_guard, subproc_confine
from agentteams.vulnscan.executor_env import ExecError
from tests.test_vulnscan_executor import env  # noqa: F401  (the shared fixture)

IDX = "registry+https://github.com/rust-lang/crates.io-index"
OLD_SUM = {"zstd": "e9" * 32, "zstd-safe": "8f" * 32}
NEW_SUM = {"zstd": "aa" * 32, "zstd-safe": "bb" * 32}
TOML = '[package]\nname = "component-host"\nversion = "0.1.0"\nedition = "2021"\n\n[dependencies]\nzstd = "0.13"\n'


def _lock(zstd: str = "0.13.3", safe: str = "7.2.4", *, extra: str = "", sums: dict | None = None) -> str:
    sums = sums or {"zstd": OLD_SUM["zstd"] if zstd == "0.13.3" else NEW_SUM["zstd"],
                    "zstd-safe": OLD_SUM["zstd-safe"] if safe == "7.2.4" else NEW_SUM["zstd-safe"]}
    return ("# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n"
            '[[package]]\nname = "component-host"\nversion = "0.1.0"\ndependencies = [\n "zstd",\n]\n\n'
            f'[[package]]\nname = "zstd"\nversion = "{zstd}"\nsource = "{IDX}"\nchecksum = "{sums["zstd"]}"\n'
            'dependencies = [\n "zstd-safe",\n]\n\n'
            f'[[package]]\nname = "zstd-safe"\nversion = "{safe}"\nsource = "{IDX}"\nchecksum = "{sums["zstd-safe"]}"\n'
            'dependencies = [\n "zstd-sys",\n]\n\n'
            f'[[package]]\nname = "zstd-sys"\nversion = "2.1.2+zstd.1.5.7"\nsource = "{IDX}"\nchecksum = "{"48" * 32}"\n'
            + extra)


#: Fixture advisories: each names an in-major fix and a next-major fix (two affected ranges).
ADVISORIES = {
    "RUSTSEC-0000-0001": ("zstd", [("0", "0.13.4"), ("0.14.0", "0.14.3")]),
    "RUSTSEC-0000-0002": ("zstd-safe", [("0", "7.4.0"), ("8.0.0", "8.2.0")]),
}


def _osv(monkeypatch: pytest.MonkeyPatch, *, still_affected: set[tuple[str, str]] = frozenset(),
         malicious: bool = False) -> None:
    def details(vid: str) -> dict:
        name, ranges = ADVISORIES[vid]
        events = [e for lo, hi in ranges for e in ({"introduced": lo}, {"fixed": hi})]
        return {"id": vid, "affected": [{"package": {"ecosystem": "crates.io", "name": name},
                                         "ranges": [{"type": "SEMVER", "events": events}]}]}

    def vulnerable(items: object) -> dict:
        out = {}
        for k in set(items):   # type: ignore[call-overload]
            eco, name, ver = k
            if (name, ver) in (("zstd", "0.13.3"), ("zstd-safe", "7.2.4")):
                out[k] = [next(v for v, (n, _r) in ADVISORIES.items() if n == name)]
            elif (name, ver) in still_affected:
                out[k] = ["MAL-0000-0001" if malicious else "RUSTSEC-0000-0009"]
        return out
    monkeypatch.setattr(osv, "details", details)
    monkeypatch.setattr(osv, "vulnerable_ids", vulnerable)


# ---------------------------------------------------------------- the target: in-major, S-10 clean

def test_the_in_major_fixed_version_is_the_target(monkeypatch: pytest.MonkeyPatch) -> None:
    _osv(monkeypatch)
    assert cargo_fix.in_major_target("zstd", "0.13.3", ["RUSTSEC-0000-0001"]) == ("0.13.4", "")
    assert cargo_fix.in_major_target("zstd-safe", "7.2.4", ["RUSTSEC-0000-0002"]) == ("7.4.0", "")


def test_an_in_major_target_with_any_advisory_is_refused_by_the_s10_search(monkeypatch: pytest.MonkeyPatch) -> None:
    _osv(monkeypatch, still_affected={("zstd", "0.13.4")})
    target, why = cargo_fix.in_major_target("zstd", "0.13.3", ["RUSTSEC-0000-0001"])
    assert target == "" and "still has advisories" in why and "S-10" in why
    _osv(monkeypatch, still_affected={("zstd", "0.13.4")}, malicious=True)
    assert cargo_fix.in_major_target("zstd", "0.13.3", ["RUSTSEC-0000-0001"]) == ("", "0.13.4 is reported malicious")


def test_without_an_in_major_fix_the_row_stays_plan_only(monkeypatch: pytest.MonkeyPatch) -> None:
    _osv(monkeypatch)
    monkeypatch.setitem(ADVISORIES, "RUSTSEC-0000-0001", ("zstd", [("0", "0.14.3")]))
    target, why = cargo_fix.in_major_target("zstd", "0.13.3", ["RUSTSEC-0000-0001"])
    assert target == "" and "stage-major work" in why


def test_the_plan_marks_stage_cargo_rows(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    _osv(monkeypatch)
    monkeypatch.setattr(osv, "minimal_fix", lambda ids, eco, name, ver: ({"zstd": "0.14.3"}.get(name, "8.2.0"), 0))
    (tmp_path / "Cargo.lock").write_text(_lock())
    rows = fix.plan_cargo_lock(tmp_path / "Cargo.lock", label="Cargo.lock")
    assert [(c.name, c.action, c.new) for c in rows] == [("zstd", "stage-cargo", "0.13.4"),
                                                         ("zstd-safe", "stage-cargo", "7.4.0")]
    assert "`cargo update -p zstd@0.13.3 --precise 0.13.4`" in rows[0].note
    (tmp_path / "Cargo.lock").write_text(_lock(extra='\n[[package]]\nname = "g"\nversion = "1.0.0"\n'
                                                     'source = "git+https://example.com/g#abc"\n'))
    rows = fix.plan_cargo_lock(tmp_path / "Cargo.lock", label="Cargo.lock")
    assert all(c.action == "plan-only" and "crates.io only" in c.note for c in rows)   # git source: refused


# ---------------------------------------------------------------- the lockfile check

MOVES = {("zstd", "0.13.3"): "0.13.4", ("zstd-safe", "7.2.4"): "7.4.0"}


def _check(new: str, planned: dict | None = MOVES) -> None:
    cargo_fix.check_lock_edit("Cargo.lock", _lock().encode(), new.encode(), planned=planned)


def test_version_and_checksum_moves_of_the_planned_crates_pass() -> None:
    _check(_lock("0.13.4", "7.4.0"))
    _check(_lock("0.13.4", "7.4.0"), planned=None)   # validate_diff's form: any in-major move


@pytest.mark.parametrize("new,match", [
    (_lock("0.14.3", "7.4.0"), "not an in-major"),                                  # a major (0.x minor) move
    (_lock("0.13.2", "7.4.0"), "not an in-major"),                                  # a downgrade
    (_lock("0.13.4-rc.1", "7.4.0"), "not an in-major"),                             # a pre-release
    (_lock("0.13.4", "7.4.0", extra='\n[[package]]\nname = "evil"\nversion = "1.0.0"\n'), "added or removed"),
    (_lock(sums={"zstd": NEW_SUM["zstd"], "zstd-safe": OLD_SUM["zstd-safe"]}), "checksum changed without"),
    (_lock("0.13.4", "7.4.0").replace(f'source = "{IDX}"\nchecksum = "{NEW_SUM["zstd"]}"',
                                      f'source = "git+https://evil/zstd"\nchecksum = "{NEW_SUM["zstd"]}"'),
     "only version, checksum"),
    (_lock("0.13.4", "7.4.0").replace(' "zstd-sys",', ' "zstd-sys 9.9.9",'), "only version"),
    (_lock("0.13.4", "7.4.0").replace(' "zstd-safe",', ' "zstd-safe 7.2.4",'), "only version"),
    (_lock("0.13.4", "7.4.0").replace("version = 4", "version = 3"), "only version, checksum"),
    (_lock("0.13.4", "7.4.0").replace('version = "0.1.0"', 'version = "0.1.1"'), "not an in-major crates.io"),
    (_lock("0.13.4", "7.4.2"), "asked for"),                                         # not the planned target
])
def test_anything_else_is_refused(new: str, match: str) -> None:
    with pytest.raises(ValueError, match=match):
        _check(new)


def test_a_dependency_reference_may_follow_its_package() -> None:
    two = _lock().replace('dependencies = [\n "zstd-safe",\n]', 'dependencies = [\n "zstd-safe 7.2.4",\n]')
    after = _lock("0.13.4", "7.4.0").replace('dependencies = [\n "zstd-safe",\n]',
                                             'dependencies = [\n "zstd-safe 7.4.0",\n]')
    cargo_fix.check_lock_edit("Cargo.lock", two.encode(), after.encode(), planned=MOVES)


# ---------------------------------------------------------------- running cargo

def _index(name: str, *, yanked: dict[str, bool] | None = None) -> str:
    """A crate's sparse-index file: the old and the in-major target release, unyanked unless ``yanked`` says so."""
    import json
    vers = {"zstd": ("0.13.3", "0.13.4"), "zstd-safe": ("7.2.4", "7.4.0")}[name]
    return "".join(json.dumps({"name": name, "vers": v, "deps": [], "cksum": "0" * 64,
                               "yanked": (yanked or {}).get(v, False)}) + "\n" for v in vers)


def _cargo_world(tmp: Path, monkeypatch: pytest.MonkeyPatch, *, writes: str | None = None,
                 confined: bool = True, rc: int = 0, index: object = None) -> list[dict]:
    (tmp / "Cargo.toml").write_text(TOML)
    (tmp / "Cargo.lock").write_text(_lock())
    (tmp / "src").mkdir()
    (tmp / "src" / "main.rs").write_text("fn main() { secret() }\n")
    (tmp / ".cargo").mkdir()
    (tmp / ".cargo" / "config.toml").write_text('[source.crates-io]\nreplace-with = "evil"\n')
    scratch = tmp.parent / f"{tmp.name}-scratch"
    scratch.mkdir(exist_ok=True)
    monkeypatch.setattr(subproc_confine, "active", lambda: subproc_confine.Confined(image="t") if confined else None)
    monkeypatch.setattr(subproc_confine, "scratch_parent", lambda: scratch)
    calls: list[dict] = []

    def run_cargo(args: list, *, workdir: Path, scratch_root: Path, env: dict, timeout: float = 600) -> object:
        calls.append({"args": list(args), "env": env, "files": sorted(
            str(p.relative_to(workdir)) for p in workdir.rglob("*") if p.is_file()),
            "main": (workdir / "src" / "main.rs").read_text()})
        name, was = args[2].split("@")
        text = (workdir / "Cargo.lock").read_text()
        now = args[4]
        text = text.replace(f'name = "{name}"\nversion = "{was}"', f'name = "{name}"\nversion = "{now}"')
        text = text.replace(OLD_SUM[name], NEW_SUM[name])
        (workdir / "Cargo.lock").write_text(writes if writes is not None else text)
        return subprocess.CompletedProcess(args, rc, "", "error: no matching package" if rc else "")

    monkeypatch.setattr(subproc_confine, "run_cargo", run_cargo)
    monkeypatch.setattr(cargo_fix, "fetch_index", index or _index)
    _osv(monkeypatch)
    monkeypatch.setattr(osv, "minimal_fix", lambda ids, eco, name, ver: ({"zstd": "0.14.3"}.get(name, "8.2.0"), 0))
    return calls


def test_stage_cargo_updates_only_the_lockfile_from_a_sourceless_scratch_copy(tmp_path: Path,
                                                                              monkeypatch: pytest.MonkeyPatch) -> None:
    calls = _cargo_world(tmp_path, monkeypatch)
    res = cargo_fix.fix_result(tmp_path, {})
    assert (tmp_path / "Cargo.lock").read_text() == _lock("0.13.4", "7.4.0")
    assert (tmp_path / "Cargo.toml").read_text() == TOML   # never copied back
    assert [c["args"] for c in calls] == [["update", "-p", "zstd@0.13.3", "--precise", "0.13.4"],
                                          ["update", "-p", "zstd-safe@7.2.4", "--precise", "7.4.0"]]
    assert calls[0]["files"] == ["Cargo.lock", "Cargo.toml", "src/main.rs"]   # no .cargo config
    assert calls[0]["main"] == ""                                               # an empty stub, never the source
    assert Path(calls[0]["env"]["CARGO_HOME"]).name == "cargo-home"
    assert [(c.name, c.action) for c in res.changes] == [("zstd", "fix"), ("zstd-safe", "fix")]
    assert res.resolved == 2 and not res.feed_errors


@pytest.mark.parametrize("case", ["outside", "cargo-fails", "extra-package"])
def test_a_run_that_cannot_be_trusted_stages_nothing(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                                     case: str) -> None:
    calls = _cargo_world(tmp_path, monkeypatch, confined=case != "outside", rc=1 if case == "cargo-fails" else 0,
                         writes=_lock(extra='\n[[package]]\nname = "x"\n') if case == "extra-package" else None)
    match = {"outside": "outside the tools container", "cargo-fails": "failed", "extra-package": "refuses cargo"}[case]
    with pytest.raises(ExecError, match=match):
        cargo_fix.fix_result(tmp_path, {})
    assert (tmp_path / "Cargo.lock").read_text() == _lock()
    assert calls == [] if case == "outside" else calls


@pytest.mark.parametrize("case,match", [
    ("yanked", "zstd 0.13.4 is yanked on crates.io"),
    ("missing-flag", "zstd 0.13.4 is yanked"),          # only an explicit "yanked": false counts as published
    ("absent", "is not in the crates.io index"),
    ("garbage", "unreadable line"),
    ("unreadable", "could not be read"),
])
def test_a_yanked_or_unknown_target_is_refused_before_cargo_runs(tmp_path: Path, monkeypatch: pytest.MonkeyPatch,
                                                                 case: str, match: str) -> None:
    def index(name: str) -> str:
        if case == "unreadable":
            raise ExecError("stage-cargo: the crates.io index for zstd could not be read; nothing is staged")
        text = _index(name, yanked={"0.13.4": True} if case == "yanked" else None)
        if name == "zstd" and case == "missing-flag":
            text = text.replace(', "yanked": false}', "}")
        if name == "zstd" and case == "absent":
            text = text.splitlines()[0] + "\n"
        if name == "zstd" and case == "garbage":
            text += "{not json\n"
        return text
    calls = _cargo_world(tmp_path, monkeypatch, index=index)
    with pytest.raises(ExecError, match=match):
        cargo_fix.fix_result(tmp_path, {})
    assert calls == [] and (tmp_path / "Cargo.lock").read_text() == _lock()


def test_the_index_is_fetched_in_the_container_through_the_index_egress(monkeypatch: pytest.MonkeyPatch) -> None:
    seen: dict = {}

    def run_confined(op: str, argv: list, **kw: object) -> object:
        seen.update(kw, argv=argv)
        return subprocess.CompletedProcess(argv, 0, _index("zstd"), "")
    monkeypatch.setattr(subproc_confine, "run_confined", run_confined)
    assert '"vers": "0.13.4"' in cargo_fix.fetch_index("zstd")
    assert seen["egress"] == (subproc_confine.CARGO_ENDPOINT,)
    assert seen["argv"][:3] == ["python3", "-I", "-c"] and seen["argv"][4] == "https://index.crates.io/zs/td/zstd"
    monkeypatch.setattr(subproc_confine, "run_confined", lambda op, argv, **kw: subprocess.CompletedProcess(
        argv, 1, "", "HTTP 503"))
    with pytest.raises(ExecError, match="could not be read"):   # fail closed
        cargo_fix.fetch_index("zstd")
    assert [cargo_fix.index_path(n) for n in ("a", "ab", "abc", "Serde")] == ["1/a", "2/ab", "3/a/abc", "se/rd/serde"]


