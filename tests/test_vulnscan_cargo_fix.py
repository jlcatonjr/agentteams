def test_cargo_egress_is_the_crates_io_index_only(monkeypatch: pytest.MonkeyPatch) -> None:
    seen: dict = {}
    monkeypatch.setattr(subproc_confine, "active", lambda: subproc_confine.Confined(image="t"))
    monkeypatch.setattr(subproc_confine, "run_confined", lambda op, argv, **kw: seen.update(kw, argv=argv) or
                        subprocess.CompletedProcess(argv, 0, "", ""))
    subproc_confine.run_cargo(["update"], workdir=Path("/tmp"), scratch_root=Path("/tmp"), env={})
    assert seen["egress"] == ("index.crates.io:443",) and seen["argv"] == ["cargo", "update"]


