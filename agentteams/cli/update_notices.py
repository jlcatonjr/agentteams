"""Notices an ``--update`` prints once, before any file is written.

* :func:`no_baseline_notice` (issue #392 item 15): a merge on a team whose ``build-log.json`` records no fence
  baseline (a team generated before the baseline existed) cannot tell an older template's text from a person's
  edit. Every fence the template changed is then preserved with its own shrink notice. One notice up front says
  why, and names the path that brings the current templates: preview ``--update --overwrite --dry-run --json``,
  review its plan and the routed agents it would orphan (item 12), then run it. ``--capture-baseline`` is not that
  path: it writes an emission snapshot, not the fence baseline. The "deleted rule … preserved-forever" notices come
  from the unfenced Constitutional Rules section and print with or without a baseline; this does not replace them.
* :func:`agentteams.cli.routing_at_risk.report_at_risk_routing` (item 12) for ``--overwrite``.

The baseline module itself (:mod:`agentteams.fence_baseline`) is pinned and is only read here.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from agentteams.cli.routing_at_risk import report_at_risk_routing

_ADVICE = (
    "     A merge cannot tell an older template's text from your edits, so each fence the template changed keeps\n"
    "     its on-disk body and prints a shrink notice. This notice stops once a merge records a baseline for the\n"
    "     fences it writes as rendered; the preserved ones stay unrecorded and keep their shrink notices. To take\n"
    "     the current templates everywhere, preview `--update --overwrite --dry-run --json`, review the plan and\n"
    "     its at_risk_routed_agents, then run it without --dry-run. --overwrite needs @security clearance and\n"
    "     replaces hand enrichment inside fences (the backup keeps it); Project-Specific Notes and Rules are\n"
    "     carried over. --capture-baseline does not help: it records an emission snapshot, not this baseline."
)
NO_BASELINE = ("  ℹ  This team has no generation baseline: references/build-log.json records no fence digests (every\n"
               "     team generated by 1.1.x or earlier).\n" + _ADVICE)
NO_BUILD_LOG = ("  ℹ  This team has no readable generation baseline: references/build-log.json is missing or "
                "malformed.\n" + _ADVICE)


def no_baseline_notice(output_dir: Path, args: Any, update_rendered: list[tuple[str, str]] | None = None) -> bool:
    """Print a no-baseline notice once on stderr for a merge on a team with no fence baseline.

    Args:
        output_dir: The team's agents directory.
        args: Parsed CLI arguments (``overwrite``).
        update_rendered: The files this update would write; a run with nothing to write prints nothing.

    Returns:
        Whether a notice was printed. Nothing prints for ``--overwrite`` (it does not use the baseline), for a run
        with nothing to write, or for an interop projection, whose build log never carries a baseline.

    Raises:
        Nothing.
    """
    from agentteams import drift, fence_baseline

    if getattr(args, "overwrite", False) or (update_rendered is not None and not update_rendered):
        return False
    try:
        log = drift.load_build_log(output_dir)
    except (FileNotFoundError, ValueError, OSError, KeyError):
        print(NO_BUILD_LOG, file=sys.stderr)
        return True
    if drift.is_interop_marker(log) or fence_baseline.load(log):
        return False
    print(NO_BASELINE, file=sys.stderr)
    return True


def report_before_write(output_dir: Path, manifest: dict, adapter: Any, update_rendered: list[tuple[str, str]],
                        args: Any) -> list[dict[str, Any]]:
    """Print the update's up-front notices and return the at-risk routed agents for the dry-run report.

    Args:
        output_dir: The team's agents directory.
        manifest: The build manifest.
        adapter: The framework adapter.
        update_rendered: The ``(relative path, content)`` pairs this update would write.
        args: Parsed CLI arguments.

    Returns:
        :func:`~agentteams.cli.routing_at_risk.report_at_risk_routing`'s entries.

    Raises:
        Nothing.
    """
    no_baseline_notice(output_dir, args, update_rendered)
    return report_at_risk_routing(output_dir, manifest, adapter, update_rendered, args)


__all__ = ["NO_BASELINE", "NO_BUILD_LOG", "no_baseline_notice", "report_before_write"]
