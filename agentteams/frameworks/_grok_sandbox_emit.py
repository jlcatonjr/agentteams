"""
_grok_sandbox_emit.py — Grok Build confinement artifacts (Phase 2b; plan tmp/by-week/2026-W42 §12.2–12.3).

Emitted for a ``--framework grok`` team when confinement is requested (``grok:sandbox`` or a confined/exclusive
``privilege_profile``) on Linux or macOS:

* ``.grok/sandbox.toml`` — profile ``agentteams``: ``extends = "workspace"`` plus a ``deny`` of secret-shaped
  files. Spike R3 showed ``read_only`` does NOT write-protect anything inside the workspace and round-2 R2-b
  showed ``deny`` also blocks reads, so this profile cannot protect agent dirs, instructions or ``.grok``. A
  relative deny glob also matches only inside the workspace (18-sandbox:148-151), so the key-directory entry
  protects a copy under the project, not ``~/.config/agentteams/keys``. It says so in its header.
* ``.grok/confined-run.example.sh`` — INERT, operator-run. ``launcher`` mode (default) runs Grok INSIDE the
  framework-neutral ``sandbox/confine-run.sh``, which is the boundary (``.grok`` and ``.claude`` whole, the
  control plane, prompt roots, masked credential dirs); Grok's own sandbox is off there because a nested
  Seatbelt/bwrap cannot start. ``profile`` mode runs ``grok --sandbox agentteams`` directly, after refusing a
  shadowing user profile or a ``requirements.toml`` sandbox pin.
* ``.grok/hooks/agentteams-gate.json`` + ``agentteams-gate-shim.py`` + ``constitutional-gate.py`` — the advisory
  PreToolUse gate (operator decision D3: only alongside the sandbox artifacts). Grok sends a Claude-shaped
  envelope with Grok tool names (spike R5); the pinned shim translates the input and runs the unmodified gate.
  Grok hooks fail open, so this is DECLARED, never enforcement. Beside the gate: ``agentteams-python`` (the
  rendering interpreter, untracked) and the ``.gitignore`` that ignores it (Rule S-8).

Integrity-pinned (``agentteams/integrity.py``), with the shim template.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

#: Paths relative to the Grok agents dir (``.grok/agents``).
GROK_SANDBOX_PROFILE_REL = "../sandbox.toml"
GROK_RUNNER_REL = "../confined-run.example.sh"
GROK_GATE_JSON_REL = "../hooks/agentteams-gate.json"
GROK_GATE_SHIM_REL = "../hooks/agentteams-gate-shim.py"
GROK_GATE_REL = "../hooks/constitutional-gate.py"
GROK_HOOKS_REL = "../hooks"
#: The ignore file beside the gate's interpreter pin (owned-marker checked like the files above).
GROK_GATE_PIN_IGNORE_REL = GROK_HOOKS_REL + "/.gitignore"

#: First line of every agentteams-owned file here; an existing file without it is never overwritten.
GROK_OWNED_MARKER = "agentteams-managed"
#: How the (unmodified) gate copy is recognised as agentteams': the template's own opening docstring.
GROK_GATE_SIGNATURE = "constitutional-gate.py — PreToolUse hook enforcing"

_TEMPLATES = Path(__file__).resolve().parents[1] / "templates" / "universal"

_PROFILE = """# agentteams-managed: .grok/sandbox.toml (regenerated by agentteams; remove this line to take it over)
#
# Select with:  grok --sandbox agentteams   (or GROK_SANDBOX=agentteams). A project file cannot activate it.
# What it does: the built-in `workspace` profile plus a kernel deny of secret-shaped files.
# What it does NOT do (Grok Build spike 2026-10-14):
#   - protect agent definitions, instructions or .grok: `read_only` entries do not write-protect anything
#     inside the workspace, and `deny` blocks reads too, so it cannot be used for files Grok must read;
#   - protect ~/.config/agentteams/keys: relative deny globs match only INSIDE the workspace, so the keys
#     entry below covers a copy under this project, nothing in your home directory.
# For the real boundary run Grok inside the agentteams launcher: .grok/confined-run.example.sh
# A profile named `agentteams` in your own ~/.grok/sandbox.toml would override this one.

[profiles.agentteams]
extends = "workspace"
deny = [
    "**/*.pem",
    "**/*.key",
    "**/.config/agentteams/keys/**",  # workspace-only (see above)
]
"""

_GATE_JSON = (
    '{"_comment": "agentteams-managed: advisory constitutional gate for Grok Build (fails open; see '
    'docs/grok-privileges)",\n'
    ' "hooks": {"PreToolUse": [{"hooks": [{"type": "command", "command": "./agentteams-gate-shim.py", '
    '"timeout": 10}]}]}}\n'
)


def grok_sandbox_feature_enabled(manifest: dict[str, Any]) -> bool:
    """Return True iff confinement is requested on this Grok manifest.

    Args:
        manifest: The team manifest.

    Returns:
        True for the ``grok:sandbox`` token or a confined/exclusive ``privilege_profile``.

    Raises:
        Nothing.
    """
    if "grok:sandbox" in (manifest.get("host_features") or []):
        return True
    return manifest.get("privilege_profile") in {"confined", "exclusive"}


def _read_template(rel: str) -> str:
    """Return a shipped template under ``templates/universal`` (raises OSError when missing)."""
    return (_TEMPLATES / rel).read_text(encoding="utf-8")


def _build_runner(manifest: dict[str, Any]) -> str:
    """Build the INERT ``.grok/confined-run.example.sh`` text (brief values only via the validated helpers)."""
    from agentteams.frameworks._codex_sandbox_emit import confined_home_bash
    from agentteams.frameworks._goose_sandbox_emit import _runner_root_expr
    from agentteams.frameworks._write_roots import runner_exclude_flags, validate_write_roots

    roots = validate_write_roots(manifest.get("workspace_write_roots") or ["."], manifest)
    writable_flags = " ".join(f"--writable {_runner_root_expr(r)}" for r in roots)
    exclude_flags, skipped_note = runner_exclude_flags(manifest)
    return (
        "#!/usr/bin/env bash\n"
        "# agentteams-managed: .grok/confined-run.example.sh - EXAMPLE: run Grok Build confined (Linux + macOS).\n"
        "# INERT / operator-run: agentteams never runs this or edits your Grok config.\n"
        "#   .grok/confined-run.example.sh [grok args]            # launcher mode (default): the real boundary\n"
        "#   GROK_CONFINE_MODE=profile .grok/confined-run.example.sh [grok args]   # Grok's own sandbox only\n"
        "#\n"
        "# LAUNCHER MODE runs Grok INSIDE sandbox/confine-run.sh, which is the boundary: writes reach only the\n"
        "# project's write roots and GROK_HOME; .grok and .claude (whole), the agentteams control plane,\n"
        "# .agentteams and the prompt roots are read-only; credential dirs (~/.config/agentteams/keys included)\n"
        "# are masked. Grok's own sandbox is OFF there (--sandbox off): it cannot nest inside bwrap/Seatbelt.\n"
        "# PROFILE MODE runs `grok --sandbox agentteams` with no launcher: only secret-shaped workspace files are\n"
        "# denied (.grok/sandbox.toml explains what it cannot protect).\n"
        "#\n"
        "# GROK_HOME: Grok writes sessions there, so it is writable for every agent command. Default\n"
        "# $HOME/.config/agentteams/grok-home/<project>-<hash>; override with AGENTTEAMS_GROK_HOME. Its user-level\n"
        "# config (config.toml, sandbox.toml, requirements.toml, trusted_folders.toml, agents/ rules/ skills/\n"
        "# hooks/ plugins/) is created empty if absent and made read-only, so a confined agent cannot plant\n"
        "# config, hooks or folder trust. Grant trust once OUTSIDE the launcher:  GROK_HOME=<dir> grok --trust\n"
        "# (or pass --trust per run: inside, it applies to that session only). Auth: XAI_API_KEY from your\n"
        "# environment is passed through; every agent command can read it.\n"
        "# Your ~/.claude config is kept out (GROK_CLAUDE_*_ENABLED=false).\n"
        "# EGRESS: host by default (Grok must reach its API); GROK_CONFINE_EGRESS=proxy + --proxy for a pinned\n"
        "# loopback proxy (see the agentteams sandboxing guide). Run as the workspace user, not root.\n"
        "set -euo pipefail\n"
        'HERE="$(cd "$(dirname "$0")" && pwd -P)"; ROOT="$(cd "$HERE/.." && pwd -P)"\n'
        'command -v grok >/dev/null 2>&1 || { echo "grok not found on PATH" >&2; exit 1; }\n'
        'export GROK_CLAUDE_HOOKS_ENABLED=false GROK_CLAUDE_SKILLS_ENABLED=false GROK_CLAUDE_MCPS_ENABLED=false\n'
        'export GROK_CLAUDE_RULES_ENABLED=false GROK_CLAUDE_AGENTS_ENABLED=false\n'
        'if [ "${GROK_CONFINE_MODE:-launcher}" = "profile" ]; then\n'
        '  # A user profile with the same name overrides the project one (18-sandbox:95); a requirements.toml\n'
        '  # pin overrides the selection. Refuse both rather than run under a profile we did not write.\n'
        '  python3 -I - "${GROK_HOME:-$HOME/.grok}" <<\'PY\' || exit 2\n'
        'import sys, tomllib\n'
        'from pathlib import Path\n'
        'home = Path(sys.argv[1])\n'
        'def load(p):\n'
        '    try:\n'
        '        return tomllib.loads(p.read_text(encoding="utf-8")) if p.is_file() else {}\n'
        '    except (OSError, ValueError) as exc:\n'
        '        sys.exit(f"REFUSING: cannot read {p}: {exc}")\n'
        'if "agentteams" in (load(home / "sandbox.toml").get("profiles") or {}):\n'
        '    sys.exit(f"REFUSING: {home}/sandbox.toml defines [profiles.agentteams], which would override the project profile")\n'
        'for req in (home / "requirements.toml", Path("/etc/grok/requirements.toml")):\n'
        '    if "sandbox" in load(req):\n'
        '        sys.exit(f"REFUSING: {req} pins [sandbox] settings that override the selected profile")\n'
        'PY\n'
        '  exec grok --sandbox agentteams "$@"\n'
        'fi\n'
        'LAUNCHER="$ROOT/sandbox/confine-run.sh"\n'
        '[ -x "$LAUNCHER" ] || { echo "neutral launcher missing at $LAUNCHER (is confinement emitted for this team?)" >&2; exit 1; }\n'
        '[ "$(id -u)" -ne 0 ] || echo "WARNING: running as root; run as the workspace user." >&2\n'
        + confined_home_bash("GROK_HOME", "grok-home", "AGENTTEAMS_GROK_HOME") +
        '# User-level config Grok trusts on its next run: create empty if absent, then protect.\n'
        'for d in agents rules skills hooks plugins personas; do mkdir -p "$GROK_HOME/$d"; done\n'
        'for f in config.toml sandbox.toml requirements.toml managed_config.toml trusted_folders.toml; do\n'
        '  [ -e "$GROK_HOME/$f" ] || : > "$GROK_HOME/$f"; done\n'
        'SCRATCH="${GROK_CONFINE_SCRATCH:-$(mktemp -d "${TMPDIR:-/tmp}/grok-confined.XXXXXX")}"\n'
        'PROTECT=()\n'
        'for p in .agentteams .agentteams-status; do [ -e "$ROOT/$p" ] && PROTECT+=( --protect "$ROOT/$p" ); done\n'
        'for f in config.toml sandbox.toml requirements.toml managed_config.toml trusted_folders.toml agents rules skills hooks plugins personas; do\n'
        '  PROTECT+=( --protect "$GROK_HOME/$f" ); done\n'
        'EGRESS="${GROK_CONFINE_EGRESS:-host}"\n'
        + skipped_note +
        '# Self-probe: inside the launcher, .grok must be unwritable and the key dir unreadable, or Grok never starts.\n'
        'PK=0; [ -n "$(ls -A "$HOME/.config/agentteams/keys" 2>/dev/null)" ] && PK=1\n'
        'SELF_PROBE=\'set -u\n'
        'if [ -d "$AGENTTEAMS_ROOT/.grok" ] && ( : >> "$AGENTTEAMS_ROOT/.grok/.agentteams-probe" ) 2>/dev/null; then\n'
        '  rm -f "$AGENTTEAMS_ROOT/.grok/.agentteams-probe"; echo "confined-run: .grok is writable inside the sandbox; refusing to start Grok" >&2; exit 3; fi\n'
        'if [ "$AGENTTEAMS_PROBE_KEYS" = 1 ] && [ -n "$(ls -A "$HOME/.config/agentteams/keys" 2>/dev/null)" ]; then\n'
        '  echo "confined-run: the operator key directory is readable inside the sandbox; refusing to start Grok" >&2; exit 3; fi\n'
        'exec grok "$@"\'\n'
        f'exec "$LAUNCHER" --scratch "$SCRATCH" {writable_flags} --writable "$GROK_HOME" \\\n'
        f'  ${{PROTECT[@]+"${{PROTECT[@]}}"}} --protect-prompt-roots{exclude_flags} --egress "$EGRESS" \\\n'
        '  --setenv GROK_HOME="$GROK_HOME" --setenv AGENTTEAMS_ROOT="$ROOT" --setenv AGENTTEAMS_PROBE_KEYS="$PK" \\\n'
        '  --setenv GROK_CLAUDE_HOOKS_ENABLED=false --setenv GROK_CLAUDE_SKILLS_ENABLED=false \\\n'
        '  --setenv GROK_CLAUDE_MCPS_ENABLED=false --setenv GROK_CLAUDE_RULES_ENABLED=false \\\n'
        '  --setenv GROK_CLAUDE_AGENTS_ENABLED=false --setenv GROK_DISABLE_AUTOUPDATER=1 \\\n'
        '  --env-allow PATH --env-allow HOME --env-allow XAI_API_KEY \\\n'
        '  -- bash -c "$SELF_PROBE" grok-confined --sandbox off "$@"\n'
    )


def grok_sandbox_output_files(manifest: dict[str, Any], platform: str | None = None) -> list[tuple[str, str]]:
    """Return the Grok confinement artifacts as ``(rel_path, content)`` pairs, or ``[]``.

    Args:
        manifest: The team manifest.
        platform: Override for ``sys.platform`` (tests).

    Returns:
        The profile, the runner example and the advisory hook gate (shim + unmodified gate + hook JSON) when
        confinement is requested on Linux or macOS; otherwise ``[]``.

    Raises:
        OSError: A shipped template is missing.
    """
    if not grok_sandbox_feature_enabled(manifest):
        return []
    plat = sys.platform if platform is None else platform
    if not (plat.startswith("linux") or plat.startswith("darwin")):
        return []
    from agentteams.frameworks.claude import _apply_fail_closed_policy, gate_interpreter_pin_files

    return [
        (GROK_SANDBOX_PROFILE_REL, _PROFILE),
        (GROK_RUNNER_REL, _build_runner(manifest)),
        (GROK_GATE_JSON_REL, _GATE_JSON),
        (GROK_GATE_SHIM_REL, _read_template("hooks/grok-gate-shim.py")),
        (GROK_GATE_REL, _apply_fail_closed_policy(_read_template("hooks/constitutional-gate.py"), manifest)),
        # The gate re-executes under this pin when the shim's python3 cannot import agentteams (untracked).
        *gate_interpreter_pin_files(GROK_HOOKS_REL),
    ]
