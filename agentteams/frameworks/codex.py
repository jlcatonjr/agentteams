def _declared_tools(content: str) -> list[str] | None:
    """Return the agent's declared tools VERBATIM (not narrowed to the canonical vocabulary).

    Bespoke agents may declare tools outside the canonical 7-token vocabulary (e.g.
    ``runCommands``); they are carried as written so the self-limit is neither narrowed nor
    widened.

    Args:
        content: A canonical agent file (Markdown with YAML front matter).

    Returns:
        The declared tools in order, or ``None`` when no ``tools:`` key is present.
    """
    yaml_text, _ = _parse_yaml_front_matter(content)
    if yaml_text is None:
        return None
    m = _capability_map._VSCODE_TOOLS_RE.search(yaml_text)
    block = _TOOLS_BLOCK_RE.search(yaml_text)
    if m:
        items = m.group(1).split(",")
    elif block:
        items = [line.strip()[1:] for line in block.group(1).splitlines() if line.strip()]
    else:
        m = _TOOLS_SCALAR_RE.search(yaml_text)
        if not m:
            return None
        items = m.group(1).split(",")
    tools = [i.strip().strip("'\"") for i in items]
    return list(dict.fromkeys(t for t in tools if t))


def _canonical(tools: list[str] | None) -> set[str] | None:
    """The declared tools as canonical tokens, or ``None`` when undeclared or bespoke."""
    toks = {t.lower() for t in tools or []}
    return toks if toks and toks <= _CANONICAL_TOOLS else None


def is_read_only(tools: list[str] | None) -> bool:
    """True when *tools* are canonical and grant no way to change the workspace: none of
    ``edit``, ``execute`` or ``retrieval`` (``agent`` and ``todo`` hand off or track work only).

    Args:
        tools: Declared tools, or ``None`` when undeclared.

    Returns:
        Whether the agent is a read-only role.
    """
    toks = _canonical(tools)
    return toks is not None and not toks & _WRITE_CAPABLE_TOOLS


def sandbox_mode_for(tools: list[str] | None) -> str | None:
    """The ``sandbox_mode`` to emit for *tools*: ``"workspace-write"`` when they declare
    ``edit``, ``"read-only"`` for any other canonical declaration (read-only roles, and
    command-running roles whose commands may not write), ``None`` when undeclared or bespoke.

    Args:
        tools: Declared tools, or ``None`` when undeclared.

    Returns:
        The sandbox mode, or ``None`` to omit the key.
    """
    toks = _canonical(tools)
    if toks is None:
        return None
    return "workspace-write" if "edit" in toks else "read-only"


def _outside_code_fences(lines: list[str]) -> list[bool]:
    flags: list[bool] = []
    in_fence = False
    for line in lines:
        if _CODE_FENCE_RE.match(line):
            flags.append(False)
            in_fence = not in_fence
            continue
        flags.append(not in_fence)
    return flags


def h1_count(markdown: str) -> int:
    """Count ATX H1 headings outside fenced code blocks.

    Args:
        markdown: Markdown text.

    Returns:
        The number of ``# `` heading lines not inside a code fence.
    """
    lines = markdown.split("\n")
    return sum(
        1 for line, outside in zip(lines, _outside_code_fences(lines))
        if outside and line.startswith("# ")
    )


def _ensure_single_leading_h1(body: str, name: str) -> str:
    """Give *body* exactly one title H1 without ever duplicating the body's own.

    The body keeps its own H1 when it has one (the normal case for a canonical agent); a
    ``# {name}`` title is prepended only when the body has none. This is the fix for the
    interop duplicate-H1 defect, where a title was prepended unconditionally.
    """
    if h1_count(body) >= 1:
        return body.strip()
    return f"# {name}\n\n{body.strip()}".strip()


def _fence_native_body(body: str) -> str:
    """Wrap an unfenced agent body in a ``content`` fence plus a Project-Specific Notes section.

    The Markdown path gets the same treatment in ``emit._normalize_generated_content`` /
    ``_ensure_project_notes_section``, but a TOML file skips it, so a natively rendered Codex agent
    used to carry its whole template body OUTSIDE every fence. ``--update --merge`` then treated
    that body as preserved-forever user content and never refreshed it (2026-10-04: agentteams'
    own agent-updater, cleanup, git-operations and security TOMLs were stale). A body that already
    has fences (a projection of a fenced ``.github`` agent) is returned unchanged.
    """
    if _ANY_FENCE_RE.search(body):
        return body
    from agentteams.fences import PROJECT_NOTES_SECTION

    return _content_wrap(body) + PROJECT_NOTES_SECTION


def retrofit_legacy_toml(text: str) -> str | None:
    """Retrofit a ``content`` fence onto a legacy Codex TOML whose agent body is unfenced.

    Only the instructions body — the text between ``developer_instructions = '''`` and the
    ``codex_translation`` fence — is wrapped; the TOML keys and the translation block stay as they
    are, so the next merge replaces the body like any other fence. Called by ``emit_all`` before it
    merges a ``.toml`` target; the pre-retrofit file is backed up there first.

    Args:
        text: The on-disk TOML.

    Returns:
        The retrofitted TOML, or None when there is nothing to do (no instructions block, no
        translation fence, or the body already carries a fence).
    """
    start = text.find(_INSTRUCTIONS_OPEN)
    block = _TRANSLATION_BLOCK_RE.search(text)
    if start < 0 or block is None or block.start() < start:
        return None
    body_start = start + len(_INSTRUCTIONS_OPEN)
    body = text[body_start:block.start()]
    if not body.strip() or _ANY_FENCE_RE.search(body):
        return None
    # Hand-written text stays OUTSIDE the fence: anything from the first Project-Specific Notes
    # heading or learned block onward is the project's, and the next merge must keep it.
    cut = _USER_TAIL_RE.search(body)
    template, tail = (body[:cut.start()], body[cut.start():]) if cut else (body, "")
    if not template.strip():
        return None
    return text[:body_start] + _content_wrap(template) + tail + text[block.start():]


def _content_wrap(text: str) -> str:
    """``text`` inside a ``content`` fence, ending with a newline."""
    return f"{_CONTENT_BEGIN}\n{text.strip()}\n{_CONTENT_END}\n"


