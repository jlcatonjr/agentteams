"""
wasm.py — Framework adapter for the agentteams WASM agent runtime (``--framework wasm``, plan P08, ARCH-B).

Agent files:  .agentteams-wasm/agents/<slug>.md  (front matter ``name, description, tools, model, delegates``)
Instructions: .agentteams-wasm/TEAM.md           (prepended to every agent's system prompt by the loader)
Sidecars:     .agentteams-wasm/grants.json, runtime.json, README.md  (+ the control-plane lock, written post-emit)
Handoffs:     stripped from the body; delegation edges live in front matter ``delegates`` (P09) and routing in
              ``references/runtime-handoffs.json`` (``handoff_delivery_mode = "manifest"``)

Unlike every other target, the "framework" here is agentteams' own runtime: each agent runs as a sequence of WASM
guest steps while the host (``agentteams.wasm_agent``) calls the model provider. The format lives in
:mod:`agentteams.wasm_agent.team` (renderer helpers and the strict loader share it); the tool translation is
:mod:`agentteams.frameworks._wasm_tool_scoping` (fail closed, no widening default).

* **WASM is on by construction** (D6, plan §4.6): ``--framework wasm`` is the opt-in
  (``wasm_config.WASM_FRAMEWORK_KEY``, reason ``framework``); an explicit off refuses — the runtime has no non-WASM
  mode. Grants come only from :func:`agentteams.sandbox_state.wasm_grant_for`; this module never reads
  ``privilege_profile``.
* **Model ids are tiers** (Rule 5): ``model:`` is ``primary`` / ``cheap`` from ``model_routing.agent_tier``; the
  template's Copilot model label is never carried over and ``runtime.json`` maps tiers to ``null`` unless the brief
  names a model.
* **No secrets**: ``runtime.json`` names a provider preset, never a key; keys come from Stage 0's environment.
* **Byte-stable**: every emitted file is a pure function of the manifest (sorted JSON, no timestamps, no absolute
  paths). The one host-dependent value is ``read_only_via`` with the OS sandbox off (``os`` where a nestable OS
  sandbox exists, else ``snapshot``).

Generate-only: not a ``--convert-from`` / ``--bridge-from`` / ``--interop-*`` / ``--absorb-from`` target or source
(refused in ``cli/parser_validate.py``), and it has no team-builder meta-agent.
"""

from __future__ import annotations

import sys
from pathlib import Path
from typing import Any

from agentteams.yaml_frontmatter import parse_yaml_front_matter as _parse_yaml_front_matter

from ._wasm_tool_scoping import parse_tools_line, translate_wasm_tools
from .agents_md import _extract_name_description, _neutralize_instructions
from .base import FrameworkAdapter

#: Manifest key (underscore: transient, excluded from the fingerprint) collecting every narrowing notice.
WASM_TOOL_NOTICES_KEY = "_wasm_tool_notices"
_TEAM_DIR = ".agentteams-wasm"
_AGENTS_DIR = (_TEAM_DIR, "agents")
_TEAM_MD_NOTICE = ("<!-- TEAM.md — generated by agentteams for the WASM agent runtime (--framework wasm). It is "
                   "prepended to every agent's system prompt; the control-plane lock refuses a hand edit. -->")


def wasm_team_state(manifest: dict[str, Any]) -> Any:
    """Return the effective sandbox state of a ``--framework wasm`` render (WASM forced on unless explicitly off).

    Args:
        manifest: The team manifest.

    Returns:
        The ``sandbox_state.SandboxState`` (``wasm`` True).

    Raises:
        ValueError: WASM is explicitly off (brief ``enabled: false`` or ``--wasm-sandbox off``), or a malformed block.
    """
    from agentteams.sandbox_state import effective_sandbox_state
    from agentteams.wasm_config import WASM_FRAMEWORK_KEY, wasm_switch

    on, reason = wasm_switch(manifest)
    if not on and reason != "default-off":
        raise ValueError(f"--framework wasm needs WASM confinement, but it is switched off ({reason})")
    return effective_sandbox_state(manifest if on else {**manifest, WASM_FRAMEWORK_KEY: True})


def _roster(yaml_text: str | None) -> list[str]:
    """The ``agents:`` block-list entries of a front matter (the orchestrator's roster)."""
    out: list[str] = []
    inside = False
    for line in (yaml_text or "").splitlines():
        if line.rstrip() == "agents:":
            inside = True
            continue
        if inside:
            item = line.strip()
            if item.startswith("- "):
                out.append(item[2:].strip().strip("'\""))
                continue
            if line and not line.startswith(" "):
                inside = False
    return out


class WasmAdapter(FrameworkAdapter):
    """Render a team for the agentteams WASM agent runtime."""

    def __init__(self) -> None:
        """Create the adapter (with a per-manifest state cache: the grant build scans read paths once)."""
        self._state: tuple[int, Any] | None = None

    @property
    def framework_id(self) -> str:
        return "wasm"

    def _team_state(self, manifest: dict[str, Any]) -> Any:
        if self._state is None or self._state[0] != id(manifest):
            self._state = (id(manifest), wasm_team_state(manifest))
        return self._state[1]

    def render_agent_file(self, content: str, agent_slug: str, manifest: dict[str, Any]) -> str:
        """Render one agent: strict front matter (tier, translated tools, delegates) + the prompt body.

        Args:
            content: The rendered template (VS Code front matter + body).
            agent_slug: The agent.
            manifest: The team manifest (mutated: :data:`WASM_TOOL_NOTICES_KEY`).

        Returns:
            The agent file.

        Raises:
            ValueError: A tool scope with no translation (``WasmToolScopeError``) or WASM explicitly off.
        """
        from agentteams.model_routing import agent_tier
        from agentteams.sandbox_state import wasm_grant_for
        from agentteams.wasm_agent.team import render_front_matter

        yaml_text, body = _parse_yaml_front_matter(content)
        name, description = _extract_name_description(content, agent_slug, manifest)
        scopes = parse_tools_line(yaml_text)
        grant = wasm_grant_for(self._team_state(manifest), agent_slug)
        team = set(manifest.get("agent_slug_list") or [])
        delegates: list[str] = []
        if scopes and "agent" in scopes:
            targets = _roster(yaml_text) + [h["agent"] for h in self.extract_handoffs(content)]
            delegates = sorted({t for t in targets if t in team and t != agent_slug})
        tools, notices = translate_wasm_tools(
            scopes, has_read_mount=any(m.guest.startswith("/project/") for m in grant.mounts),
            has_scratch=any(m.guest == "/scratch" for m in grant.mounts), has_delegates=bool(delegates),
            agent=agent_slug)
        for notice in notices:
            print(f"  [WASM-SCOPE] {notice}", file=sys.stderr)
        manifest.setdefault(WASM_TOOL_NOTICES_KEY, []).extend(notices)
        body = self._strip_handoffs_section(body).replace(".github/agents", "/".join(_AGENTS_DIR)).strip()
        head = render_front_matter(name=name, description=description, tools=tools,
                                   model=agent_tier(agent_slug, manifest), delegates=delegates)
        return f"{head}\n{body}\n"

    def render_instructions_file(self, content: str, manifest: dict[str, Any]) -> str:
        """Render ``TEAM.md``: the neutralised team instructions (no vendor branding or paths).

        Args:
            content: The rendered instructions template.
            manifest: The team manifest.

        Returns:
            The TEAM.md text.

        Raises:
            Nothing.
        """
        from ._agents_md_rules import apply_constitutional_rules_baseline

        body = apply_constitutional_rules_baseline(self._strip_yaml_front_matter(content), manifest)
        body = _neutralize_instructions(body, agents_dir="/".join(_AGENTS_DIR))
        return f"{_TEAM_MD_NOTICE}\n\n{body}".strip() + "\n"

    def extra_output_files(self, manifest: dict[str, Any]) -> list[tuple[str, str]]:
        """Return the neutral baseline plus ``grants.json``, ``runtime.json`` and ``README.md``.

        Args:
            manifest: The team manifest.

        Returns:
            ``(agents-dir-relative path, content)`` pairs.

        Raises:
            ValueError: WASM explicitly off, a malformed ``wasm_runtime`` block, or a mount outside the project.
        """
        from agentteams.frameworks._wasm_team_docs import grants_document, readme_text
        from agentteams.wasm_agent.team import dumps, runtime_record

        state = self._team_state(manifest)
        runtime = runtime_record(manifest.get("wasm_runtime"), os_on=state.os)
        grants = grants_document(manifest, state, host_os_confine=runtime["host_os_confine"])
        return [*super().extra_output_files(manifest), ("../grants.json", dumps(grants)),
                ("../runtime.json", dumps(runtime)), ("../README.md", readme_text(manifest, state, runtime, grants))]

    def get_file_extension(self, file_type: str) -> str:
        return ".md"

    def required_front_matter_keys(self) -> tuple[str, ...]:
        """Exactly the keys the loader accepts (``wasm_agent.team.FRONT_MATTER_KEYS``)."""
        from agentteams.wasm_agent.team import FRONT_MATTER_KEYS

        return FRONT_MATTER_KEYS

    def supports_handoffs(self) -> bool:
        return False

    def handoff_delivery_mode(self) -> str:
        return "manifest"

    def get_agents_dir(self, project_path: Path) -> Path:
        return project_path.joinpath(*_AGENTS_DIR)

    def normalize_output_path(self, output: Path) -> Path:
        """Append ``.agentteams-wasm/agents`` to a project-root ``--output`` (mirrors grok/codex).

        Args:
            output: The ``--output`` path.

        Returns:
            The agents directory under *output*.

        Raises:
            Nothing.
        """
        parts = output.parts
        if len(parts) >= 2 and parts[-2:] == _AGENTS_DIR:
            return output
        if parts and parts[-1] == _TEAM_DIR:
            return output / _AGENTS_DIR[1]
        return output.joinpath(*_AGENTS_DIR)

    def finalize_output_path(self, rel_path: str, file_type: str) -> str:
        """Place the instructions at ``.agentteams-wasm/TEAM.md`` (one level above the agents dir).

        Args:
            rel_path: The planned path.
            file_type: The logical file type.

        Returns:
            The framework path.

        Raises:
            Nothing.
        """
        if file_type == "instructions" and rel_path.endswith("copilot-instructions.md"):
            return "../TEAM.md"
        return super().finalize_output_path(rel_path, file_type)


def write_team_lock(agents_dir: Path) -> Path | None:
    """Hash the just-emitted team into ``.agentteams/wasm-team.lock.json`` (the post-emit step of every write path).

    Args:
        agents_dir: The team's agents dir (``<root>/.agentteams-wasm/agents``).

    Returns:
        The lock path, or None when it could not be written (printed: the launcher then refuses the team).

    Raises:
        Nothing.
    """
    from agentteams.wasm_agent.team import LOCK_REL, TeamError, write_lock

    root = Path(agents_dir).parent.parent
    try:
        path = write_lock(root)
    except (OSError, TeamError) as exc:
        print(f"  !  WASM team lock not written ({exc}); --run-wasm-agent refuses this team until a re-render "
              "writes it.", file=sys.stderr)
        return None
    print(f"  ✓  WASM team locked: {LOCK_REL}")
    return path


__all__ = ["WASM_TOOL_NOTICES_KEY", "WasmAdapter", "wasm_team_state", "write_team_lock"]
