"""
_agents_md_ownership.py — who may write the shared repo-root ``AGENTS.md``.

Several targets read or write the one repo-root ``AGENTS.md``: ``--framework agents-md``, ``codex``, ``goose``
and ``grok``, plus hand-written files. This module owns the shared ownership markers and the classification
every guard uses, so no adapter can lock another out by accident and none can overwrite text it did not write.

* Each generating adapter opens its ``AGENTS.md`` with a generated notice whose first characters are its
  marker (``CODEX_AGENTS_MD_MARKER``, ``GROK_AGENTS_MD_MARKER``, ``NEUTRAL_AGENTS_MD_MARKER``).
* :func:`classify_agents_md` says who owns an existing file. A marker counts only at the very start of the
  file (after leading whitespace): a marker quoted later in the text never confers ownership.
* :func:`upsert_fenced_block` adds or refreshes ONE fenced block without touching any byte outside it.

Integrity-pinned (``agentteams/integrity.py``): this module decides whether a file someone else wrote may be
modified (@security step-6 ruling, tmp/by-week/2026-W42/grok-integration.plan.md §11 condition 5).
"""

from __future__ import annotations

import os
import re
from pathlib import Path

CODEX_AGENTS_MD_MARKER = "<!-- AGENTS.md — generated by agentteams for OpenAI Codex."
GROK_AGENTS_MD_MARKER = "<!-- AGENTS.md — generated by agentteams for Grok Build."
#: Prefix of ``agents_md._AGENTS_MD_NOTICE`` (the framework-neutral ``--framework agents-md`` render).
NEUTRAL_AGENTS_MD_MARKER = "<!-- AGENTS.md — generated by agentteams. "

#: The fence holding Grok-specific notes inside a shared AGENTS.md.
GROK_FENCE_ID = "grok_runtime"

#: Classifications returned by :func:`classify_agents_md`.
ABSENT, GROK, CODEX, AGENTS_MD, FENCED, FOREIGN, UNSAFE = (
    "absent", "grok", "codex", "agents-md", "agentteams-fenced", "foreign", "unsafe",
)

_HEAD_CHARS = 512


def symlink_on_path(path: Path, root: Path) -> Path | None:
    """Return the first symlink on the lexical chain from *path* up to *root*, else None.

    *root* itself is not checked (the project root may legitimately be reached through a link); every
    component below it is, *path* included. Judged lexically (no resolution), so a link cannot hide itself.

    Args:
        path: The path to check.
        root: The project root bounding the walk.

    Returns:
        The first symlinked component, or None.

    Raises:
        Nothing.
    """
    current = Path(os.path.normpath(path))
    root = Path(os.path.normpath(root))
    while current != root and current.parent != current:
        if current.is_symlink():
            return current
        current = current.parent
    return None


def classify_agents_md(path: Path, *, repo_root: Path | None = None) -> str:
    """Classify the repo-root ``AGENTS.md`` at *path* by owner.

    Args:
        path: The ``AGENTS.md`` path, lexically normalised (unresolved).
        repo_root: The project root. When given, a symlinked component between it and *path*, or a target that
            resolves outside it, classifies as ``unsafe``.

    Returns:
        One of ``absent``, ``grok``, ``codex``, ``agents-md``, ``agentteams-fenced`` (agentteams fences but no
        marker: goose, legacy renders, or a hand file the operator fenced), ``foreign`` (no marker, no fence) or
        ``unsafe`` (a symlink, an unreadable or non-UTF-8 file, malformed fences, or a path escaping the root).

    Raises:
        Nothing.
    """
    path = Path(os.path.normpath(path))
    if path.is_symlink():
        return UNSAFE  # dangling or not, a link would redirect the write
    if repo_root is not None:
        if symlink_on_path(path.parent, repo_root) is not None:
            return UNSAFE
        try:
            if not path.parent.resolve().is_relative_to(Path(repo_root).resolve()):
                return UNSAFE
        except OSError:
            return UNSAFE
    if not path.exists():
        return ABSENT
    if not path.is_file():
        return UNSAFE
    try:
        text = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return UNSAFE
    head = text.lstrip()[:_HEAD_CHARS]
    if head.startswith(GROK_AGENTS_MD_MARKER):
        return GROK
    if head.startswith(CODEX_AGENTS_MD_MARKER):
        return CODEX
    if head.startswith(NEUTRAL_AGENTS_MD_MARKER):
        return AGENTS_MD
    from agentteams.fences import _extract_fenced_regions

    regions = _extract_fenced_regions(text)
    if isinstance(regions, str):
        return UNSAFE
    return FENCED if regions else FOREIGN


def fence_pattern(fence_id: str) -> re.Pattern[str]:
    """Return the regex matching one complete ``fence_id`` fence (BEGIN with ``v=N`` through END).

    Args:
        fence_id: The fence's section id.

    Returns:
        A DOTALL pattern; the one definition every grok/AGENTS.md fence edit uses.

    Raises:
        Nothing.
    """
    sid = re.escape(fence_id)
    return re.compile(
        rf"<!--\s*AGENTTEAMS:BEGIN\s+{sid}\s+v=\d+\s*-->.*?<!--\s*AGENTTEAMS:END\s+{sid}\s*-->",
        re.DOTALL,
    )


def upsert_fenced_block(existing: str, fence_id: str, block: str) -> str:
    """Add or replace one fenced block, leaving every byte outside it unchanged.

    Args:
        existing: The current file text.
        fence_id: The fence's section id (e.g. ``grok_runtime``).
        block: The complete fenced block, BEGIN and END markers included.

    Returns:
        *existing* with the fence's span replaced by *block*, or with *block* appended after the text (one blank
        line between) when the fence is absent.

    Raises:
        ValueError: *block* is not a single well-formed fence for *fence_id*, or *existing* holds the fence more
            than once or with an unmatched BEGIN/END.
    """
    pattern = fence_pattern(fence_id)
    if not pattern.fullmatch(block.strip()):
        raise ValueError(f"block is not one well-formed {fence_id!r} fence")
    matches = list(pattern.finditer(existing))
    sid = re.escape(fence_id)
    begins = len(re.findall(rf"<!--\s*AGENTTEAMS:BEGIN\s+{sid}\s", existing))  # stray halves count too
    ends = len(re.findall(rf"<!--\s*AGENTTEAMS:END\s+{sid}\s", existing))
    if len(matches) > 1 or begins != len(matches) or ends != len(matches):
        raise ValueError(f"existing text holds a duplicate or unbalanced {fence_id!r} fence; refusing to edit it")
    block = block.strip()
    if matches:
        m = matches[0]
        return existing[: m.start()] + block + existing[m.end():]
    return existing.rstrip("\n") + "\n\n" + block + "\n"


def strip_agents_md_notice(text: str) -> str:
    """Remove one leading Grok or Codex generated notice from *text* (an adapter re-stamping its own render).

    Args:
        text: Instructions content, possibly read back from a generated AGENTS.md.

    Returns:
        The content without the notice (left-stripped); unchanged when it carries none.

    Raises:
        Nothing.
    """
    out = strip_all_ownership_notices(text, limit=1, markers=(GROK_AGENTS_MD_MARKER, CODEX_AGENTS_MD_MARKER))
    return out if out is text else out.lstrip()


def strip_all_ownership_notices(
    text: str,
    *,
    limit: int | None = None,
    markers: tuple[str, ...] = (GROK_AGENTS_MD_MARKER, CODEX_AGENTS_MD_MARKER, NEUTRAL_AGENTS_MD_MARKER),
) -> str:
    """Remove EVERY leading generated ownership notice (Grok, Codex, neutral), however many are stacked.

    Interop uses this before writing a CAI's instructions into another target: one strip would leave a second
    stacked notice behind, and the target file would then classify as owned by a framework that never wrote it
    (ownership spoofing; @security Phase 3 condition 2).

    A marker with no closing ``-->`` still loses its whole first line: :func:`classify_agents_md` looks only at the
    marker prefix, so a crafted unclosed notice must not survive into the target either.

    Args:
        text: Instructions content from a CAI (data, possibly crafted).
        limit: Stop after this many notices (None: all).
        markers: The markers to strip.

    Returns:
        The content with the leading notices removed; the same object when there was none.

    Raises:
        Nothing.
    """
    count = 0
    while limit is None or count < limit:
        stripped = text.lstrip()
        if not any(stripped.startswith(m) for m in markers):
            return text
        if "-->" in stripped:
            text = stripped.split("-->", 1)[1]
        else:
            text = stripped.split("\n", 1)[1] if "\n" in stripped else ""
        count += 1
    return text


def strip_fence(text: str, fence_id: str) -> str:
    """Remove every ``fence_id`` fenced block (BEGIN through END) from *text*.

    Args:
        text: The file or instructions text.
        fence_id: The fence's section id (e.g. ``grok_runtime``).

    Returns:
        *text* without those blocks; surrounding blank lines collapsed to one.

    Raises:
        Nothing.
    """
    return re.sub(rf"\n*{fence_pattern(fence_id).pattern}\n*", "\n\n", text, flags=re.DOTALL)

